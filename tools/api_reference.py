"""Generate the API reference of the documentation site from the docstrings.

The reference lists every name of `pyropdf.__all__`, grouped by the module
that defines it, with its signature and docstring, and for a class each
public method and property with its own. Each section is a page of
docs/en/api/, beside an index of all of them. It is generated, so it cannot
drift from the package.

Run it after changing a public docstring or signature:

    uv run python tools/api_reference.py

With `--check` it writes nothing and fails when a page of docs/en/api/
differs from what the package generates, or when mkdocs.yml does not list
it. tests/test_docs.py runs that check.
"""

from __future__ import annotations

import argparse
import enum
import inspect
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "python" / "pyropdf"
OUTPUT = Path("docs/en/api")
NAV = ROOT / "mkdocs.yml"
COMMAND = "uv run python tools/api_reference.py"

#: The sections of the reference, in order, and the modules each gathers.
SECTIONS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("Documents", ("_document",)),
    ("Metadata", ("_metadata",)),
    ("Page labels", ("_page_labels",)),
    ("Images", ("_images",)),
    ("Layers", ("_layers",)),
    ("Sanitizing", ("_sanitize",)),
    ("Fonts", ("_fonts",)),
    ("Pages", ("_pages", "_page")),
    ("Drawing", ("_canvas",)),
    ("Text and content", ("_text", "_content", "_tables", "_markdown")),
    ("OCR", ("_ocr",)),
    ("Rendering", ("_pixmap",)),
    ("Annotations", ("_annotations",)),
    ("Links and destinations", ("_links", "_targets")),
    ("Forms and widgets", ("_form", "_widgets")),
    ("Outline", ("_outline",)),
    ("Attachments", ("_attachments",)),
    ("History and changes", ("_history", "_changes")),
    ("Encryption", ("_encryption",)),
    ("Signing", ("_signing",)),
    ("Limits and errors", ("_limits", "_errors")),
    ("Content operations", ("_operations",)),
    ("Objects", ("_objects",)),
    ("Geometry", ("_geometry",)),
    ("Checks and profiles", ("_check", "_profiles")),
    ("Typed objects", ("typed",)),
)

#: The names that the Rust extension defines, by the module whose section
#: they belong to, and the `typed` submodule.
EXTENSION = {
    "CancellationToken": "_limits",
    "Pixmap": "_pixmap",
    "typed": "typed",
} | dict.fromkeys(
    (
        "DocumentClosedError",
        "EncryptedDocumentError",
        "LimitError",
        "MalformedPdfError",
        "OcrError",
        "PasswordError",
        "PdfError",
        "StaleObjectError",
    ),
    "_errors",
)

#: The longest signature kept on one line, as ruff formats the package.
WIDTH = 88

NOTICE = f"""\
<!-- Generated by tools/api_reference.py from the package's docstrings. Do
not edit this file: change the docstring and run `{COMMAND}`. -->
"""

INDEX = f"""\
---
title: API reference
description: Every public name of pyropdf, with its signature and docstring, by topic.
---

{NOTICE}
# API reference

Every name that `import pyropdf` exports, grouped by topic. Signatures and
descriptions come from the package itself. Each topic's page gives every
method and property of its classes with its full description.
"""


def _definitions() -> dict[str, str]:
    """Map each top-level class, function, and alias to the module that defines it."""
    pattern = re.compile(r"^(?:class|def) ([A-Za-z_]\w*)|^([A-Z]\w*)(?:: TypeAlias)? = ", re.MULTILINE)
    found: dict[str, str] = {}
    for path in sorted(PACKAGE.glob("*.py")):
        for match in pattern.finditer(path.read_text(encoding="utf-8")):
            found.setdefault(match.group(1) or match.group(2), path.stem)
    return found | EXTENSION


def _doc(obj: object) -> str:
    """Return the cleaned docstring of an object, with reST roles as code."""
    text = inspect.cleandoc(getattr(obj, "__doc__", None) or "")
    text = re.sub(r":(?:class|meth|attr|func|data|exc|mod):`~?([^`]+)`", r"`\1`", text)
    return text.replace("``", "`")


def _signature(obj: object, name: str = "") -> str:
    """Return `name` called with the signature of a callable, one parameter per line when long.

    A callable without a signature gives an empty string.
    """
    try:
        signature = inspect.signature(obj)  # ty: ignore[invalid-argument-type]
    except (TypeError, ValueError):
        return ""
    parameters = list(signature.parameters.values())
    if parameters and parameters[0].name in {"self", "cls"}:
        parameters = parameters[1:]
    # Postponed annotations are strings; show them as written, not quoted.
    parameters = [
        p.replace(annotation=_Written(p.annotation)) if isinstance(p.annotation, str) else p for p in parameters
    ]
    returned = signature.return_annotation
    if returned is None or returned == "None":
        returned = inspect.Signature.empty
    elif isinstance(returned, str):
        returned = _Written(returned)
    text = name + str(signature.replace(parameters=parameters, return_annotation=returned))
    text = text.replace("=Ellipsis", "=...")
    if len(text) <= WIDTH or not parameters:
        return text
    # The signature's own text places the `/` and `*` markers between the parameters.
    listed = str(signature.replace(parameters=parameters, return_annotation=inspect.Signature.empty))
    inner = _split_parameters(listed[1:-1].replace("=Ellipsis", "=..."))
    tail = text[len(name) + len(listed) :]
    return f"{name}(\n" + "".join(f"    {part},\n" for part in inner) + f"){tail}"


def _split_parameters(text: str) -> list[str]:
    """Split a parameter list at its top-level commas."""
    parts, depth, start = [], 0, 0
    for index, char in enumerate(text):
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(text[start:index].strip())
            start = index + 1
    parts.append(text[start:].strip())
    return parts


class _Written:
    """An annotation that formats as its source text."""

    def __init__(self, text: str) -> None:
        self.text = text

    def __repr__(self) -> str:
        return self.text


def _summary(obj: object) -> str:
    """Return the first paragraph of a docstring, on one line."""
    return " ".join(_doc(obj).split("\n\n", 1)[0].split())


def _members(cls: type, owner: str) -> list[str]:
    """Return the public methods and properties that a class defines itself, each with its docstring."""
    entries = []
    members = vars(cls).items()
    if any(inspect.isgetsetdescriptor(member) or inspect.ismethoddescriptor(member) for _, member in members):
        # The extension's classes list their members in hash order; sort them.
        members = sorted(members)
    for name, member in members:
        if name.startswith("_") and name not in {"__init__", "__iter__", "__len__", "__getitem__"}:
            continue
        attribute = isinstance(member, property) or inspect.isgetsetdescriptor(member)
        if name == "__init__" or not (callable(member) or attribute or isinstance(member, classmethod | staticmethod)):
            continue
        target = member.__func__ if isinstance(member, classmethod | staticmethod) else member
        qualified = f"{owner}.{name}"
        if attribute:
            code = qualified + _property_type(member)
            text = _noun(_doc(member))
            if getattr(member, "fset", None) is not None:
                text = f"{text}\n\nSettable." if text else "Settable."
        else:
            code = _signature(target, qualified) or qualified
            text = _doc(target)
        entries.append("\n\n".join(part for part in (f"### `{qualified}`", f"```python\n{code}\n```", text) if part))
    return entries


def _property_type(member: object) -> str:
    """Return `: type` for a property whose getter names its type."""
    getter = getattr(member, "fget", None)
    returned = inspect.signature(getter).return_annotation if getter is not None else inspect.Signature.empty
    if returned is inspect.Signature.empty:
        return ""
    return f": {returned if isinstance(returned, str) else inspect.formatannotation(returned)}"


def _noun(text: str) -> str:
    """Word a property's docstring as what it is: "Return the pages" becomes "The pages"."""
    match = re.match(r"Returns? (\w)", text)
    if match is None:
        return text
    return match.group(1).upper() + text[match.end() :]


def _entry(name: str, obj: object) -> str:
    """Return the reference text of one exported name."""
    if isinstance(obj, type) and issubclass(obj, enum.Enum):
        values = ", ".join(f"`{member.name}`" for member in obj)
        return f"## `{name}`\n\n{_doc(obj)}\n\nMembers: {values}.\n"
    if isinstance(obj, type):
        init = vars(obj).get("__init__")
        signature = _signature(init, name) if init is not None else ""
        parts = [f"## `{name}`", f"```python\n{signature}\n```" if signature else "", _doc(obj), *_members(obj, name)]
        return "\n\n".join(part for part in parts if part) + "\n"
    if inspect.ismodule(obj):
        return f"## `pyropdf.{name}`\n\n{_doc(obj)}\n"
    if callable(obj) and inspect.isroutine(obj):
        return f"## `{name}`\n\n```python\n{_signature(obj, name)}\n```\n\n{_doc(obj)}\n"
    return f"## `{name}`\n\n`{name} = {obj!r}`\n"


def _described(obj: object) -> str:
    """Return the summary of a name that has a docstring of its own, else an empty string.

    An alias such as a union would show its type's docstring, which differs
    between Python versions.
    """
    own = isinstance(obj, type) or inspect.ismodule(obj) or inspect.isroutine(obj)
    return _summary(obj) if own else ""


def _slug(title: str) -> str:
    """Return the file name of a section's page."""
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def _anchors(page: str) -> dict[str, str]:
    """Return the anchor of each `## `name`` heading, as Python-Markdown's toc makes them unique."""
    anchors, seen = {}, set()
    for level, heading in re.findall(r"^(#{1,3}) (.+)$", page, re.MULTILINE):
        anchor = re.sub(r"[-\s]+", "-", re.sub(r"[^\w\s-]", "", heading).strip().lower())
        unique, number = anchor, 0
        while unique in seen:
            number += 1
            unique = f"{anchor}_{number}"
        seen.add(unique)
        if level == "##":
            anchors[heading.strip("`").removeprefix("pyropdf.")] = unique
    return anchors


def generate() -> dict[str, str]:
    """Return the text of each page of the API reference, by file name."""
    # The installed package, which `uv run` rebuilds; CI installs it without
    # an editable link, so the checkout's python/ has no extension to import.
    import pyropdf  # noqa: PLC0415

    modules = _definitions()
    exported = [name for name in pyropdf.__all__ if not name.startswith("__")]
    unplaced = {name for name in exported if modules.get(name) not in {m for _, ms in SECTIONS for m in ms}}
    if unplaced:
        message = f"no section for {sorted(unplaced)}: add their modules to SECTIONS"
        raise SystemExit(message)
    pages = {}
    index = [INDEX]
    for title, section_modules in SECTIONS:
        names = sorted((n for n in exported if modules[n] in section_modules), key=str.lower)
        if not names:
            continue
        slug = _slug(title)
        description = f"The pyropdf API reference for {title.lower()}."
        header = f"---\ntitle: {title}\ndescription: {description}\n---\n\n{NOTICE}\n# {title}\n"
        text = [header, *(_entry(name, getattr(pyropdf, name)) for name in names)]
        page = textwrap.dedent("\n".join(text)).rstrip() + "\n"
        pages[f"{slug}.md"] = page
        anchors = _anchors(page)
        index.append(f"## [{title}]({slug}.md)\n")
        links = (f"- [`{n}`]({slug}.md#{anchors[n]}): {_described(getattr(pyropdf, n))}".rstrip(": ") for n in names)
        index.append("\n".join(links) + "\n")
    pages["index.md"] = "\n".join(index).rstrip() + "\n"
    return pages


def main() -> None:
    """Write the reference, or with `--check` compare it."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the reference is out of date")
    args = parser.parse_args()
    directory = ROOT / OUTPUT
    pages = generate()
    nav = NAV.read_text(encoding="utf-8")
    unlisted = [name for name in pages if f"api/{name}" not in nav]
    if unlisted:
        sys.exit(f"{NAV.name} does not list {', '.join(f'api/{name}' for name in unlisted)}")
    existing = {path.name for path in directory.glob("*.md")}
    if args.check:
        stale = sorted(existing - pages.keys())
        changed = sorted(
            n
            for n, text in pages.items()
            if not (directory / n).exists() or (directory / n).read_text(encoding="utf-8") != text
        )
        if stale or changed:
            sys.exit(f"{OUTPUT} is out of date ({', '.join(stale + changed)}): run `{COMMAND}`")
        return
    directory.mkdir(parents=True, exist_ok=True)
    for name in existing - pages.keys():
        (directory / name).unlink()
    for name, text in pages.items():
        (directory / name).write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
