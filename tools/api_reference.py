class _Written:
    """An annotation or default value that formats as its source text."""

    def __init__(self, text: str) -> None:
        self.text = text

    def __repr__(self) -> str:
        return self.text


@dataclass(frozen=True)
class _StubMember:
    """One property or callable parsed from `_core.pyi`."""

    kind: str
    signature: inspect.Signature | None = None
    type_text: str = ""


@dataclass
class _SourceInfo:
    """Static metadata gathered from the package's `.py` and `.pyi` sources."""

    modules: dict[str, str] = field(default_factory=dict)
    attr_docs: dict[str, str] = field(default_factory=dict)
    top_annotations: dict[str, str] = field(default_factory=dict)
    type_aliases: dict[str, str] = field(default_factory=dict)
    class_constants: dict[str, list[tuple[str, str]]] = field(default_factory=dict)
    class_bases: dict[tuple[str, str], list[str]] = field(default_factory=dict)
    stubs: dict[str, dict[str, _StubMember]] = field(default_factory=dict)


def _clean_doc(raw: str) -> str:
    """Clean a docstring or `#:` comment, rendering reST roles as code without breaking fences."""
    text = inspect.cleandoc(raw)
    text = re.sub(r":(?:class|meth|attr|func|data|exc|mod):`~?([^`]+)`", r"`\1`", text)
    return re.sub(r"(?<!`)``(?!`)", "`", text)


def _doc(obj: object) -> str:
    """Return the cleaned docstring of an object, with reST roles as code."""
    target = obj.__func__ if isinstance(obj, classmethod | staticmethod) else obj
    return _clean_doc(getattr(target, "__doc__", None) or "")


def _preceding_comment(lines: list[str], lineno: int) -> str:
    """Return the `#:` block immediately preceding 1-based `lineno`, or an empty string."""
    collected: list[str] = []
    index = lineno - 2
    while index >= 0:
        stripped = lines[index].lstrip()
        if not stripped.startswith("#:"):
            break
        collected.append(stripped[2:].removeprefix(" "))
        index -= 1
    collected.reverse()
    return _clean_doc("\n".join(collected)) if collected else ""


def _clean_type_expr(text: str) -> str:
    """Strip module prefixes that clutter source annotations."""
    return re.sub(r"\btyping\.", "", text)


def _format_alias(name: str, rhs: ast.expr, *, explicit_keyword: bool) -> str:
    """Format a top-level `TypeAlias` definition wrapped to `WIDTH`."""
    prefix = f"{name}: TypeAlias = " if explicit_keyword else f"{name} = "
    single = prefix + _clean_type_expr(ast.unparse(rhs))
    if len(single) <= WIDTH:
        return single
    if isinstance(rhs, ast.Subscript) and _clean_type_expr(ast.unparse(rhs.value)) == "Literal":
        elts = rhs.slice.elts if isinstance(rhs.slice, ast.Tuple) else [rhs.slice]
        items = "".join(f"    {_clean_type_expr(ast.unparse(elt))},\n" for elt in elts)
        return f"{prefix}Literal[\n{items}]"
    union_parts = _flatten_bit_or(rhs)
    if len(union_parts) > 1:
        first, *rest = (_clean_type_expr(ast.unparse(part)) for part in union_parts)
        joined = f"    {first}\n" + "".join(f"    | {item}\n" for item in rest)
        return f"{prefix}(\n{joined})"
    return single


def _flatten_bit_or(expr: ast.expr) -> list[ast.expr]:
    """Flatten a chain of `a | b | c` AST nodes iteratively."""
    parts: list[ast.expr] = []
    current = expr
    while isinstance(current, ast.BinOp) and isinstance(current.op, ast.BitOr):
        parts.append(current.right)
        current = current.left
    parts.append(current)
    parts.reverse()
    return parts


def _base_names(node: ast.ClassDef) -> list[str]:
    """Return the non-private direct base expressions of a class definition."""
    bases: list[str] = []
    for base in node.bases:
        head = base.value if isinstance(base, ast.Subscript) else base
        raw = ast.unparse(head).split(".")[-1]
        if raw in _OMITTED_BASES or raw.startswith("_"):
            continue
        bases.append(_clean_type_expr(ast.unparse(base)))
    return bases


def _collect_class_constants(node: ast.ClassDef, lines: list[str], info: _SourceInfo) -> None:
    """Extract public `ClassVar[...]` declarations and their `#:` comments from a class body."""
    statements: list[ast.stmt] = []
    for stmt in node.body:
        if isinstance(stmt, ast.If) and ast.unparse(stmt.test) == "TYPE_CHECKING":
            statements.extend(stmt.body)
        else:
            statements.append(stmt)
    for stmt in statements:
        if not (isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name)):
            continue
        const_name = stmt.target.id
        if const_name.startswith("_") or not isinstance(stmt.annotation, ast.Subscript):
            continue
        if _clean_type_expr(ast.unparse(stmt.annotation.value)) != "ClassVar":
            continue
        inner = _clean_type_expr(ast.unparse(stmt.annotation.slice))
        info.class_constants.setdefault(node.name, []).append((const_name, inner))
        comment = _preceding_comment(lines, stmt.lineno)
        if comment:
            info.attr_docs.setdefault(f"{node.name}.{const_name}", comment)


def _stub_signature(fn: ast.FunctionDef) -> inspect.Signature:
    """Build an `inspect.Signature` from a stub `FunctionDef` AST node."""
    args = fn.args
    positional = [*args.posonlyargs, *args.args]
    pos_defaults: list[ast.expr | None] = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)
    parameters: list[inspect.Parameter] = []
    for index, (arg, default) in enumerate(zip(positional, pos_defaults, strict=True)):
        kind = (
            inspect.Parameter.POSITIONAL_ONLY
            if index < len(args.posonlyargs)
            else inspect.Parameter.POSITIONAL_OR_KEYWORD
        )
        parameters.append(_stub_param(arg, kind, default))
    if args.vararg is not None:
        parameters.append(_stub_param(args.vararg, inspect.Parameter.VAR_POSITIONAL, None))
    for arg, default in zip(args.kwonlyargs, args.kw_defaults, strict=True):
        parameters.append(_stub_param(arg, inspect.Parameter.KEYWORD_ONLY, default))
    if args.kwarg is not None:
        parameters.append(_stub_param(args.kwarg, inspect.Parameter.VAR_KEYWORD, None))
    if parameters and parameters[0].name in {"self", "cls"}:
        parameters = parameters[1:]
    returned: object = inspect.Signature.empty
    if fn.returns is not None:
        ret_text = _clean_type_expr(ast.unparse(fn.returns))
        if ret_text != "None":
            returned = _Written(ret_text)
    return inspect.Signature(parameters=parameters, return_annotation=returned)


def _stub_param(arg: ast.arg, kind: inspect._ParameterKind, default: ast.expr | None) -> inspect.Parameter:
    """Convert one AST parameter and optional default into an `inspect.Parameter`."""
    ann: object = (
        _Written(_clean_type_expr(ast.unparse(arg.annotation)))
        if arg.annotation is not None
        else inspect.Parameter.empty
    )
    dft: object = inspect.Parameter.empty
    if default is not None:
        dft_text = _clean_type_expr(ast.unparse(default))
        dft = _Written("..." if dft_text == "..." else dft_text)
    return inspect.Parameter(arg.arg, kind, default=dft, annotation=ann)


def _scan_python_file(path: Path, module: str, info: _SourceInfo) -> None:
    """Scan one `.py` file for module definitions, aliases, `#:` docs, bases, and class constants."""
    source = path.read_text(encoding="utf-8")
    lines = source.splitlines()
    tree = ast.parse(source, filename=str(path))
    namespace = "typed" if module == "typed" else "pyropdf"
    for node in tree.body:
        if isinstance(node, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            info.modules.setdefault(node.name, module)
            if isinstance(node, ast.ClassDef):
                bases = _base_names(node)
                if bases:
                    info.class_bases[(namespace, node.name)] = bases
                _collect_class_constants(node, lines, info)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            target_name = node.target.id
            info.modules.setdefault(target_name, module)
            ann_text = _clean_type_expr(ast.unparse(node.annotation))
            if ann_text == "TypeAlias" and node.value is not None:
                info.type_aliases.setdefault(target_name, _format_alias(target_name, node.value, explicit_keyword=True))
            else:
                info.top_annotations.setdefault(f"{module}.{target_name}", ann_text)
                info.top_annotations.setdefault(target_name, ann_text)
            comment = _preceding_comment(lines, node.lineno)
            if comment:
                info.attr_docs.setdefault(f"{module}.{target_name}", comment)
                info.attr_docs.setdefault(target_name, comment)
        elif isinstance(node, ast.Assign):
            _scan_assign(node, lines, module, info)


def _scan_assign(node: ast.Assign, lines: list[str], module: str, info: _SourceInfo) -> None:
    """Record top-level constant assignments, `Literal` aliases, and `<Name>.__doc__` strings."""
    for target in node.targets:
        if isinstance(target, ast.Name):
            name = target.id
            info.modules.setdefault(name, module)
            if isinstance(node.value, ast.Subscript) and _clean_type_expr(ast.unparse(node.value.value)) == "Literal":
                info.type_aliases.setdefault(name, _format_alias(name, node.value, explicit_keyword=False))
            comment = _preceding_comment(lines, node.lineno)
            if comment:
                info.attr_docs.setdefault(f"{module}.{name}", comment)
                info.attr_docs.setdefault(name, comment)
        elif (
            isinstance(target, ast.Attribute)
            and target.attr == "__doc__"
            and isinstance(target.value, ast.Name)
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        ):
            info.attr_docs.setdefault(target.value.id, _clean_doc(node.value.value))


def _scan_stub(info: _SourceInfo) -> None:
    """Parse `python/pyropdf/_core.pyi` for extension signatures, bases, and `__version__`."""
    source = STUB.read_text(encoding="utf-8")
    lines = source.splitlines()
    tree = ast.parse(source, filename=str(STUB))
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            name = node.target.id
            info.top_annotations[name] = _clean_type_expr(ast.unparse(node.annotation))
            comment = _preceding_comment(lines, node.lineno)
            if comment:
                info.attr_docs[name] = comment
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            bases = _base_names(node)
            if bases:
                info.class_bases[("pyropdf", node.name)] = bases
            members: dict[str, _StubMember] = {}
            for item in node.body:
                if not isinstance(item, ast.FunctionDef):
                    continue
                decorators = {_clean_type_expr(ast.unparse(dec)) for dec in item.decorator_list}
                if "property" in decorators:
                    ret = _clean_type_expr(ast.unparse(item.returns)) if item.returns is not None else ""
                    members[item.name] = _StubMember(kind="property", type_text=ret)
                elif item.name == "__init__":
                    members["__init__"] = _StubMember(kind="init", signature=_stub_signature(item))
                else:
                    members[item.name] = _StubMember(kind="method", signature=_stub_signature(item))
            info.stubs[node.name] = members


def _load_source_info() -> _SourceInfo:
    """Gather AST metadata across `python/pyropdf` and `_core.pyi`."""
    info = _SourceInfo()
    for path in [*sorted(PACKAGE.glob("*.py")), *sorted(PACKAGE.glob("_*/*.py"))]:
        module = path.stem if path.parent == PACKAGE else path.parent.name
        _scan_python_file(path, module, info)
    _scan_stub(info)
    info.modules |= EXTENSION
    return info


def _format_flag_default(value: enum.Flag) -> str:
    """Format an `Enum`/`Flag` default value as valid Python syntax."""
    cls = type(value)
    cls_name = cls.__name__
    for member_name, member in cls.__members__.items():
        if member.value == value.value:
            return f"{cls_name}.{member_name}"
    raw_int = int(value.value)
    if raw_int == 0:
        return f"{cls_name}(0)"
    bits = [
        f"{cls_name}.{member_name}"
        for member_name, member in cls.__members__.items()
        if member.value and (raw_int & int(member.value)) == int(member.value) and int(member.value).bit_count() == 1
    ]
    covered = 0
    for member in cls.__members__.values():
        mval = int(member.value)
        if mval and (raw_int & mval) == mval and mval.bit_count() == 1:
            covered |= mval
    if bits and covered == raw_int:
        return " | ".join(bits)
    return f"{cls_name}({raw_int})"


def _format_default(value: object, depth: int = 0) -> str:
    """Format a runtime parameter default as valid Python syntax without `<...: ...>` reprs."""
    if depth >= _MAX_FORMAT_DEPTH:
        return repr(value)
    if value is Ellipsis:
        return "..."
    if isinstance(value, enum.Enum):
        return _format_flag_default(value) if isinstance(value, enum.Flag) else f"{type(value).__name__}.{value.name}"
    if isinstance(value, tuple):
        inner = (
            f"{_format_default(value[0], depth + 1)},"
            if len(value) == 1
            else ", ".join(_format_default(item, depth + 1) for item in value)
        )
        return f"({inner})"
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        parts = [
            f"{fld.name}={_format_default(getattr(value, fld.name), depth + 1)}"
            for fld in dataclasses.fields(value)
            if fld.repr
        ]
        return f"{type(value).__name__}({', '.join(parts)})"
    return repr(value)


def _format_signature(signature: inspect.Signature, name: str = "", *, is_constructor: bool = False) -> str:
    """Render an `inspect.Signature` under `name`, wrapping parameters past `WIDTH`."""
    parameters = list(signature.parameters.values())
    if parameters and parameters[0].name in {"self", "cls"}:
        parameters = parameters[1:]
    normalized: list[inspect.Parameter] = []
    for param in parameters:
        ann = _Written(param.annotation) if isinstance(param.annotation, str) else param.annotation
        dft = (
            param.default
            if param.default is inspect.Parameter.empty or isinstance(param.default, _Written)
            else _Written(_format_default(param.default))
        )
        normalized.append(param.replace(annotation=ann, default=dft))
    returned = inspect.Signature.empty if is_constructor else signature.return_annotation
    if returned is None or returned == "None":
        returned = inspect.Signature.empty
    elif isinstance(returned, str):
        returned = _Written(returned)
    clean_sig = signature.replace(parameters=normalized, return_annotation=returned)
    text = name + str(clean_sig)
    if len(text) <= WIDTH or not normalized:
        return text
    # The signature's own text places the `/` and `*` markers between the parameters.
    listed = str(signature.replace(parameters=normalized, return_annotation=inspect.Signature.empty))
    inner = _split_parameters(listed[1:-1])
    tail = text[len(name) + len(listed) :]
    return f"{name}(\n" + "".join(f"    {part},\n" for part in inner) + f"){tail}"


def _signature(obj: object, name: str = "", *, is_constructor: bool = False) -> str:
    """Return `name` called with the signature of a callable, one parameter per line when long."""
    try:
        signature = inspect.signature(obj)  # ty: ignore[invalid-argument-type]
    except (TypeError, ValueError):
        return ""
    return _format_signature(signature, name, is_constructor=is_constructor)


def _split_parameters(text: str) -> list[str]:
    """Split a parameter list at its top-level commas."""
    parts, depth, start = [], 0, 0
    for index, char in enumerate(text):
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(text[start:index].strip())
            start = index + 1
    parts.append(text[start:].strip())
    return parts


def _unalias_typed(text: str, *, is_typed: bool) -> str:
    """Replace `typed.py`'s internal `_Dictionary`/`_Array` aliases with `pyropdf.*`."""
    if not is_typed:
        return text
    text = re.sub(r"\b_Dictionary\b", "pyropdf.Dictionary", text)
    return re.sub(r"\b_Array\b", "pyropdf.Array", text)


def _summary(obj: object) -> str:
    """Return the first paragraph of a docstring, on one line."""
    return " ".join(_doc(obj).split("\n\n", 1)[0].split())


def _is_package_type(cls: type) -> bool:
    """Return whether `cls` is defined by `pyropdf` rather than stdlib or builtins."""
    return cls.__module__ == "pyropdf" or cls.__module__.startswith("pyropdf.")


def _format_tuple_constant(qualified: str, type_text: str, values: tuple[str, ...]) -> str:
    """Format a small string-tuple constant with its items."""
    single = f"{qualified}: {type_text} = {values!r}"
    if len(single) <= WIDTH:
        return single
    items = "".join(f"    {item!r},\n" for item in values)
    return f"{qualified}: {type_text} = (\n{items})"


def _stub_members(cls: type, owner: str, stubs: dict[str, _StubMember]) -> list[str]:
    """Render the members of a Rust extension class using `_core.pyi` types and runtime docstrings."""
    missing = sorted(name for name in vars(cls) if not name.startswith("_") and name not in stubs)
    if missing:
        msg = f"{STUB.name} is missing {cls.__name__} members: {', '.join(missing)}"
        raise SystemExit(msg)
    entries: list[str] = []
    for name in sorted(stubs):
        if name in {"__init__", "__buffer__"}:
            continue
        stub = stubs[name]
        runtime = vars(cls).get(name)
        qualified = f"{owner}.{name}"
        if stub.kind == "property":
            code = f"{qualified}: {stub.type_text}" if stub.type_text else qualified
            text = _noun(_doc(runtime)) if runtime is not None else ""
        else:
            assert stub.signature is not None  # noqa: S101
            code = _format_signature(stub.signature, qualified)
            text = _doc(runtime) if runtime is not None else ""
        entries.append("\n\n".join(part for part in (f"### `{qualified}`", f"```python\n{code}\n```", text) if part))
    return entries


def _class_constant_entries(cls: type, owner: str, info: _SourceInfo) -> tuple[list[str], set[str]]:
    """Render public `ClassVar` constants inherited or defined by `cls`."""
    entries: list[str] = []
    seen: set[str] = set()
    for base in reversed([b for b in cls.__mro__ if _is_package_type(b)]):
        for const_name, const_type in info.class_constants.get(base.__name__, ()):
            if const_name in seen or not hasattr(cls, const_name):
                continue
            seen.add(const_name)
            qualified = f"{owner}.{const_name}"
            value = getattr(cls, const_name)
            if isinstance(value, tuple) and len(value) <= _MAX_INLINE_TUPLE and all(isinstance(x, str) for x in value):
                code = _format_tuple_constant(qualified, const_type, value)
            else:
                code = f"{qualified}: {const_type}"
            text = info.attr_docs.get(f"{base.__name__}.{const_name}", "")
            entries.append(
                "\n\n".join(part for part in (f"### `{qualified}`", f"```python\n{code}\n```", text) if part)
            )
    return entries, seen


def _tuplegetter_type(base: type, name: str) -> str:
    """Return `: type` for a `NamedTuple` field descriptor on `base`."""
    annotations = getattr(base, "__annotations__", {})
    ann = annotations.get(name)
    if ann is None:
        return ""
    if isinstance(ann, str):
        return f": {ann}"
    forward = getattr(ann, "__forward_arg__", None)
    if isinstance(forward, str):
        return f": {forward}"
    return f": {inspect.formatannotation(ann)}"


def _render_member(qualified: str, defining_base: type, name: str, member: object, *, is_typed: bool) -> str:
    """Format one collected property, tuple field, or method entry."""
    if type(member).__name__ == "_tuplegetter":
        code = qualified + _tuplegetter_type(defining_base, name)
        raw_doc = _doc(member)
        text = "" if raw_doc.startswith("Alias for field number ") else _noun(raw_doc)
    elif isinstance(member, property) or inspect.isgetsetdescriptor(member):
        code = qualified + _unalias_typed(_property_type(member), is_typed=is_typed)
        text = _noun(_doc(member))
        if getattr(member, "fset", None) is not None:
            text = f"{text}\n\nSettable." if text else "Settable."
    else:
        target = member.__func__ if isinstance(member, classmethod | staticmethod) else member
        code = _unalias_typed(_signature(target, qualified), is_typed=is_typed) or qualified
        text = _doc(target)
    return "\n\n".join(part for part in (f"### `{qualified}`", f"```python\n{code}\n```", text) if part)


def _members(cls: type, owner: str, info: _SourceInfo) -> list[str]:
    """Return the public constants, properties, methods, and documented dunders of `cls`."""
    if cls.__name__ in info.stubs and not owner.startswith("typed."):
        return _stub_members(cls, owner, info.stubs[cls.__name__])
    is_typed = owner.startswith("typed.")
    entries, constant_names = _class_constant_entries(cls, owner, info)
    collected: dict[str, tuple[type, object]] = {}
    for base in reversed([b for b in cls.__mro__ if _is_package_type(b)]):
        for name, member in vars(base).items():
            if name in constant_names:
                continue
            if name.startswith("_") and not (
                name in _CONTAINER_DUNDERS or (name in _DOCUMENTED_DUNDERS and bool(_doc(member)))
            ):
                continue
            is_attr = (
                isinstance(member, property)
                or inspect.isgetsetdescriptor(member)
                or type(member).__name__ == "_tuplegetter"
            )
            if callable(member) or is_attr or isinstance(member, classmethod | staticmethod):
                collected[name] = (base, member)
    entries.extend(
        _render_member(f"{owner}.{name}", defining_base, name, member, is_typed=is_typed)
        for name, (defining_base, member) in collected.items()
    )
    return entries


def _property_type(member: object) -> str:
    """Return `: type` for a property whose getter names its type."""
    getter = getattr(member, "fget", None)
    returned = inspect.signature(getter).return_annotation if getter is not None else inspect.Signature.empty
    if returned is inspect.Signature.empty:
        return ""
    return f": {returned if isinstance(returned, str) else inspect.formatannotation(returned)}"


def _noun(text: str) -> str:
    """Word a property's docstring as what it is: 'Return or set the pages' becomes 'The pages'."""
    match = re.match(r"Returns?(?: or sets?)? (\w|`)", text)
    if match is None:
        return text
    return match.group(1).upper() + text[match.end() :]


def _new_constructors(name: str, new: object) -> list[str]:
    """Return constructor signatures from `__new__` and any `@overload` forms."""
    target = new.__func__ if isinstance(new, staticmethod) else new
    if _doc(target).startswith("Refuse"):
        return []
    overloads = typing.get_overloads(target)  # ty: ignore[invalid-argument-type]
    if overloads:
        return [sig for ov in overloads if (sig := _signature(ov, name, is_constructor=True))]
    sig = _signature(target, name, is_constructor=True)
    return [sig] if sig else []


def _constructors(name: str, cls: type, info: _SourceInfo) -> list[str]:
    """Return the typed constructor call signatures of `cls`, omitting factory-only classes."""
    is_typed = name.startswith("typed.")
    if cls.__name__ in info.stubs and not is_typed:
        init_stub = info.stubs[cls.__name__].get("__init__")
        if init_stub is not None and init_stub.signature is not None:
            return [_format_signature(init_stub.signature, name, is_constructor=True)]
        return []
    init = vars(cls).get("__init__")
    if init is not None:
        sig = (
            ""
            if _doc(init).startswith("Refuse")
            else _unalias_typed(_signature(init, name, is_constructor=True), is_typed=is_typed)
        )
        return [sig] if sig else []
    new = vars(cls).get("__new__")
    if new is not None:
        return _new_constructors(name, new)
    if cls.__name__ == "String" and cls.__module__ in {"pyropdf", "pyropdf._objects"}:
        return list(_STRING_CONSTRUCTORS)
    return []


def _class_header(name: str, cls: type, info: _SourceInfo) -> str:
    """Build the declaration and constructor block shown under `## `ClassName``."""
    namespace = "typed" if name.startswith("typed.") else "pyropdf"
    bases = info.class_bases.get((namespace, cls.__name__), [])
    lines: list[str] = []
    if bases:
        lines.append(f"class {cls.__name__}({', '.join(bases)})")
    lines.extend(_constructors(name, cls, info))
    return f"```python\n{chr(10).join(lines)}\n```" if lines else ""


def _entry(name: str, obj: object, info: _SourceInfo, attr_doc: str = "", module_key: str = "") -> str:
    """Return the reference text of one exported name."""
    if isinstance(obj, type) and issubclass(obj, enum.Enum):
        values = ", ".join(f"`{member}`" for member in obj.__members__)
        return f"## `{name}`\n\n{_doc(obj)}\n\nMembers: {values}.\n"
    if isinstance(obj, type):
        header = _class_header(name, obj, info)
        parts = [f"## `{name}`", header, _doc(obj), *_members(obj, name, info)]
        return "\n\n".join(part for part in parts if part) + "\n"
    if inspect.ismodule(obj):
        return f"## `pyropdf.{name}`\n\n{_doc(obj)}\n"
    if callable(obj) and inspect.isroutine(obj):
        return f"## `{name}`\n\n```python\n{_signature(obj, name)}\n```\n\n{_doc(obj)}\n"
    if name in info.type_aliases:
        value = f"```python\n{info.type_aliases[name]}\n```"
    elif isinstance(obj, Mapping):
        items = "".join(f"    {key!r}: {value_item!r},\n" for key, value_item in obj.items())
        value = f"```python\n{name} = {{\n{items}}}\n```"
    elif ann := info.top_annotations.get(f"{module_key}.{name}" if module_key else name) or info.top_annotations.get(
        name
    ):
        value = f"```python\n{name}: {ann}\n```"
    else:
        value = f"`{name} = {obj!r}`"
    return "\n\n".join(part for part in (f"## `{name}`", value, attr_doc) if part) + "\n"


def _described(obj: object, attr_doc: str = "") -> str:
    """Return the summary of a name that has a docstring of its own, else an empty string.

    An alias such as a union would show its type's docstring, which differs
    between Python versions.
    """
    own = isinstance(obj, type) or inspect.ismodule(obj) or inspect.isroutine(obj)
    if own:
        return _summary(obj)
    return " ".join(attr_doc.split("\n\n", 1)[0].split()) if attr_doc else ""


def _slug(title: str) -> str:
    """Return the file name of a section's page."""
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def _anchors(page: str) -> dict[str, str]:
    """Return the anchor of each `## `name`` heading, as Python-Markdown's toc makes them unique."""
    anchors, seen = {}, set()
    for level, heading in re.findall(r"^(#{1,3}) (.+)$", page, re.MULTILINE):
        anchor = re.sub(r"[-\s]+", "-", re.sub(r"[^\w\s-]", "", heading).strip().lower())
        unique, number = anchor, 0
        while unique in seen:
            number += 1
            unique = f"{anchor}_{number}"
        seen.add(unique)
        if level == "##":
            anchors[heading.strip("`").removeprefix("pyropdf.")] = unique
    return anchors


def _section_items(
    section_modules: tuple[str, ...],
    exported: list[str],
    pyropdf_mod: object,
    info: _SourceInfo,
) -> list[tuple[str, object, str, str]]:
    """Build `(display_name, obj, attr_doc, module_key)` items for one reference section."""
    names = sorted((n for n in exported if info.modules[n] in section_modules), key=str.lower)
    items: list[tuple[str, object, str, str]] = []
    for name in names:
        obj = getattr(pyropdf_mod, name)
        mod_key = info.modules[name]
        doc = info.attr_docs.get(f"{mod_key}.{name}") or info.attr_docs.get(name, "")
        items.append((name, obj, doc, mod_key))
        if inspect.ismodule(obj) and name == "typed":
            for sub_name in sorted(getattr(obj, "__all__", ()), key=str.lower):
                sub_obj = getattr(obj, sub_name)
                sub_doc = info.attr_docs.get(f"typed.{sub_name}", "")
                items.append((f"typed.{sub_name}", sub_obj, sub_doc, "typed"))
    return items


def generate() -> dict[str, str]:
    """Return the text of each page of the API reference, by file name."""
    # The installed package, which `uv run` rebuilds; CI installs it without
    # an editable link, so the checkout's python/ has no extension to import.
    import pyropdf  # noqa: PLC0415

    info = _load_source_info()
    exported = list(pyropdf.__all__)
    known_modules = {m for _, ms in SECTIONS for m in ms}
    unplaced = {name for name in exported if info.modules.get(name) not in known_modules}
    if unplaced:
        message = f"no section for {sorted(unplaced)}: add their modules to SECTIONS"
        raise SystemExit(message)
    pages = {}
    index = [INDEX]
    for title, section_modules in SECTIONS:
        items = _section_items(section_modules, exported, pyropdf, info)
        if not items:
            continue
        slug = _slug(title)
        description = f"The pyropdf API reference for {title.lower()}."
        header = f"---\ntitle: {title}\ndescription: {description}\n---\n\n{NOTICE}\n# {title}\n"
        text = [header, *(_entry(disp, obj, info, doc, mod_key) for disp, obj, doc, mod_key in items)]
        page = textwrap.dedent("\n".join(text)).rstrip() + "\n"
        pages[f"{slug}.md"] = page
        anchors = _anchors(page)
        index.append(f"## [{title}]({slug}.md)\n")
        links = (
            f"- [`{disp}`]({slug}.md#{anchors[disp]}): {_described(obj, doc)}".rstrip(": ")
            for disp, obj, doc, _ in items
        )
        index.append("\n".join(links) + "\n")
    pages["index.md"] = "\n".join(index).rstrip() + "\n"
    return pages


def main() -> None:
    """Write the reference, or with `--check` compare it."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the reference is out of date")
    args = parser.parse_args()
    directory = ROOT / OUTPUT
    pages = generate()
    nav = NAV.read_text(encoding="utf-8")
    unlisted = [name for name in pages if f"api/{name}" not in nav]
    if unlisted:
        sys.exit(f"{NAV.name} does not list {', '.join(f'api/{name}' for name in unlisted)}")
    existing = {path.name for path in directory.glob("*.md")}
    if args.check:
        stale = sorted(existing - pages.keys())
        changed = sorted(
            n
            for n, text in pages.items()
            if not (directory / n).exists() or (directory / n).read_text(encoding="utf-8") != text
        )
        if stale or changed:
            sys.exit(f"{OUTPUT} is out of date ({', '.join(stale + changed)}): run `{COMMAND}`")
        return
    directory.mkdir(parents=True, exist_ok=True)
    for name in existing - pages.keys():
        (directory / name).unlink()
    for name, text in pages.items():
        (directory / name).write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
