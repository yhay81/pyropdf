# ruff: noqa: INP001, S603, S607, T201 - Standalone evidence script invoking installed PDF readers.
"""Verify a full-save redaction of a fixed text and image fixture."""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import tempfile
from pathlib import Path
from xml.etree import ElementTree as ET

import pikepdf
import pymupdf

import pyropdf

WIDTH, HEIGHT = 8, 4
RGB_COMPONENTS = 3
COVERED = {y * WIDTH + x for y in (1, 2) for x in range(2, 6)}
KEPT = ("LEFT", "RIGHT")
ORIGINAL = ("LEFT", "SECRET", "RIGHT", "HUSH")
TOLERANCE = 0.001  # PDF points, within each individual reader.
SOURCE = bytes(v for y in range(HEIGHT) for x in range(WIDTH) for v in (5 + 20 * x, 11 + 50 * y, 80 + x + WIDTH * y))
# PDF page coordinates, with the page origin at lower left.
COVER_IMAGE = b"q 1 g 40 20 40 20 re f Q"
# PyMuPDF uses the top left. Each small rectangle intersects only the designated glyphs or pixels.
REGIONS = ((53, 24, 101, 31), (53, 47, 83, 55), (40.01, 90.01, 79.99, 109.99))

Box = tuple[float, float, float, float]
Words = list[tuple[str, Box]]


def make_source(path: Path) -> None:
    """Create visible and invisible text above a small, unambiguously coloured image."""
    with pikepdf.Pdf.new() as pdf:
        page = pdf.add_blank_page(page_size=(200, 130))
        font = pdf.make_indirect(
            pikepdf.Dictionary(Type=pikepdf.Name.Font, Subtype=pikepdf.Name.Type1, BaseFont=pikepdf.Name.Helvetica)
        )
        image = pdf.make_stream(SOURCE)
        image.Type, image.Subtype = pikepdf.Name.XObject, pikepdf.Name.Image
        image.Width, image.Height = WIDTH, HEIGHT
        image.BitsPerComponent, image.ColorSpace = 8, pikepdf.Name.DeviceRGB
        page.Resources = pikepdf.Dictionary(Font=pikepdf.Dictionary(F=font), XObject=pikepdf.Dictionary(Im=image))
        page.Contents = pdf.make_stream(
            b"q 80 0 0 40 20 10 cm /Im Do Q\n"
            b"BT /F 12 Tf 1 0 0 1 20 100 Tm [(LEFT ) (SECRET) ( RIGHT)] TJ ET\n"
            b"BT /F 8 Tf 3 Tr 1 0 0 1 55 77 Tm (HUSH) Tj ET"
        )
        pdf.save(path, static_id=True)


def readers(path: Path) -> dict[str, Words]:
    """Read all words and their boxes independently in three engines."""
    with pyropdf.open(path) as doc:
        public = [(w.text, (w.bbox.x0, w.bbox.y0, w.bbox.x1, w.bbox.y1)) for w in doc.pages[0].words()]
    with pymupdf.open(path) as doc:
        mupdf = [(w[4], (w[0], w[1], w[2], w[3])) for w in doc[0].get_text("words")]
    xhtml = subprocess.check_output(["pdftotext", "-bbox", str(path), "-"])
    words = ET.fromstring(xhtml).findall(".//{*}word")  # noqa: S314 - generated by pdftotext.
    poppler: Words = []
    for word in words:
        a = word.attrib
        poppler.append((word.text or "", (float(a["xMin"]), float(a["yMin"]), float(a["xMax"]), float(a["yMax"]))))
    return {"pyropdf": public, "PyMuPDF": mupdf, "Poppler": poppler}


def rgb_space(space: object) -> bool:
    """Recognize both the source's RGB space and the reference writer's tagged RGB space."""
    if not isinstance(space, pikepdf.Array):
        return space == pikepdf.Name.DeviceRGB
    if len(space) != 2:  # noqa: PLR2004 - [ /ICCBased profile ].
        return False
    tag, profile = space
    return (
        tag == pikepdf.Name.ICCBased
        and isinstance(profile, pikepdf.Stream)
        and profile.get("/N") == RGB_COMPONENTS
        and profile.read_bytes()[16:20] == b"RGB "
    )


def inspect_samples(path: Path) -> tuple[int, int, int] | None:
    """Count correct covered and outside samples in the fixture's one stored RGB image."""
    with pikepdf.open(path) as pdf:
        images = [
            obj for obj in pdf.objects if isinstance(obj, pikepdf.Stream) and obj.get("/Subtype") == pikepdf.Name.Image
        ]
        if len(images) != 1:
            return None
        image = images[0]
        if (image.get("/Width"), image.get("/Height"), image.get("/BitsPerComponent")) != (WIDTH, HEIGHT, 8):
            return None
        if not rgb_space(image.get("/ColorSpace")):
            return None
        if image.get("/ImageMask", False) or any(key in image for key in ("/SMask", "/Mask")):
            return None
        if list(image.get("/Decode", [0, 1] * 3)) != [0, 1] * 3:
            return None
        data = image.read_bytes()
    covered = outside = 0
    for y in range(HEIGHT):
        for x in range(WIDTH):
            offset = (y * WIDTH + x) * 3
            pixel = data[offset : offset + 3]
            if y * WIDTH + x in COVERED:
                covered += pixel == b"\xff\xff\xff"
            else:
                outside += pixel == SOURCE[offset : offset + 3]
    return covered, outside, len(data)


def painted_image_matches(pixels: bytes) -> int:
    """Check the centre of each source pixel where the page places it."""
    matching = 0
    for y in range(HEIGHT):
        for x in range(WIDTH):
            offset = 3 * ((85 + 10 * y) * 200 + 25 + 10 * x)
            source_offset = 3 * (y * WIDTH + x)
            expected = SOURCE[source_offset : source_offset + 3]
            if y * WIDTH + x in COVERED:
                expected = b"\xff\xff\xff"
            matching += pixels[offset : offset + 3] == expected
    return matching


def check(path: Path, before: dict[str, Words], reference_pixels: bytes) -> dict:
    """Compare a candidate with the reading order, retained boxes and source samples."""
    readings = {}
    failures: list[str] = []
    with pymupdf.open(path) as pdf:
        revisions = pdf.version_count
        if revisions != 1:
            failures.append("full save")
        if len(pdf) != 1:
            failures.append("page count")
    for reader, words in readers(path).items():
        tokens = [text for text, _ in words]
        if tuple(tokens) != KEPT:
            failures.append(f"{reader} text")
        original = dict(before[reader])
        retained = {text: box for text, box in words if text in KEPT}
        drift = None
        if set(retained) == set(KEPT):
            drift = max(abs(a - b) for text in KEPT for a, b in zip(original[text], retained[text], strict=True))
        if drift is None or drift > TOLERANCE:
            failures.append(f"{reader} positions")
        readings[reader] = {"words": tokens, "max_drift_pt": drift}
    samples = inspect_samples(path)
    if samples != (8, 24, len(SOURCE)):
        failures.append("stored image")
    pixels = appearance(path)
    text_end = 3 * 200 * 75  # The image starts at row 80.
    if pixels[:text_end] != reference_pixels[:text_end]:
        failures.append("painted text")
    matching = painted_image_matches(pixels)
    if matching != WIDTH * HEIGHT:
        failures.append("painted image")
    return {
        "revisions": revisions,
        "readers": readings,
        "image_samples": samples,
        "painted_matches": matching,
        "failures": failures,
    }


def make_controls(work: Path, source: Path, reference: Path) -> None:
    """Construct the reference and isolate each observable failure."""
    with pymupdf.open(source) as pdf:
        page = pdf[0]
        for region in REGIONS:
            page.add_redact_annot(region, fill=False)
        page.apply_redactions(
            images=pymupdf.PDF_REDACT_IMAGE_PIXELS,
            graphics=pymupdf.PDF_REDACT_LINE_ART_NONE,
            text=pymupdf.PDF_REDACT_TEXT_REMOVE,
        )
        pdf.save(reference, garbage=4, clean=True, deflate=True)
    with pikepdf.open(source) as pdf:
        page = pdf.pages[0]
        page.contents_add(b"q 1 g 52 94 51 20 re f Q\n" + COVER_IMAGE)
        pdf.save(work / "overlay.pdf")
    with pikepdf.open(reference) as pdf:
        page = pdf.pages[0]
        image_name = str(next(iter(page.Resources.XObject.keys())))
        font_name = str(next(iter(page.Resources.Font.keys())))
        page.Contents = pdf.make_stream(
            f"q 80 0 0 40 20 10 cm {image_name} Do Q BT {font_name} 12 Tf 20 100 Td (LEFT) Tj "
            "87.684 0 Td (RIGHT) Tj ET".encode()
        )
        pdf.save(work / "shifted.pdf")
    with pikepdf.open(reference) as pdf:
        page = pdf.pages[0]
        next(iter(page.Resources.XObject.values())).write(SOURCE)
        page.contents_add(COVER_IMAGE)
        pdf.save(work / "covered-image.pdf")
    with pikepdf.open(reference) as pdf:
        page = pdf.pages[0]
        page.contents_add(b"q 1 g 20 10 80 40 re f Q")
        pdf.save(work / "covered-whole-image.pdf")
    with pikepdf.open(reference) as pdf:
        pdf.pages[0].contents_add(b"q 1 g 19 94 32 20 re f Q")
        pdf.save(work / "covered-kept-word.pdf")
    with pikepdf.open(reference) as pdf:
        pdf.save(work / "linearized.pdf", linearize=True)
    incremental = work / "incremental.pdf"
    shutil.copyfile(reference, incremental)
    with pymupdf.open(incremental) as pdf:
        pdf.set_metadata({"title": "Second revision"})
        pdf.saveIncr()


def appearance(path: Path) -> bytes:
    """Render the independent image-overlay control with Poppler at 72 dpi."""
    raster = subprocess.check_output(["pdftoppm", "-singlefile", "-r", "72", str(path)])
    if not raster.startswith(b"P6\n200 130\n255\n") or len(raster.split(b"\n", 3)[-1]) != 200 * 130 * 3:
        message = "Unexpected Poppler output for the 200 by 130 point fixture"
        raise ValueError(message)
    return raster.split(b"\n", 3)[-1]


def main() -> None:
    """Write the fixture, exercise the controls and optionally verify another full save."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("scratch", type=Path)
    parser.add_argument("--candidate", type=Path, help="full save made from the generated original.pdf")
    args = parser.parse_args()
    args.scratch.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="redaction-", dir=args.scratch.resolve()))
    source, reference = work / "original.pdf", work / "reference.pdf"
    make_source(source)
    before = readers(source)
    if not all(tuple(text for text, _ in words) == ORIGINAL for words in before.values()):
        message = f"Unexpected original words: {before}"
        raise ValueError(message)
    make_controls(work, source, reference)
    expected = {
        "reference": set(),
        "linearized": set(),
        "incremental": {"full save"},
        "covered-kept-word": {"painted text"},
        "overlay": {"pyropdf text", "PyMuPDF text", "Poppler text", "stored image"},
        "shifted": {"pyropdf positions", "PyMuPDF positions", "Poppler positions", "painted text"},
        "covered-image": {"stored image"},
        "covered-whole-image": {"painted image"},
    }
    reference_pixels = appearance(reference)
    reports = {name: check(work / f"{name}.pdf", before, reference_pixels) for name in expected}
    for name, failures in expected.items():
        if set(reports[name]["failures"]) != failures:
            message = f"Unexpected {name} outcome: {reports[name]}"
            raise ValueError(message)
    if reference_pixels != appearance(work / "covered-image.pdf"):
        message = "The covered-image control differs visually from the reference"
        raise ValueError(message)
    if args.candidate:
        reports["candidate"] = check(args.candidate, before, reference_pixels)
    (work / "results.json").write_text(json.dumps(reports, indent=2) + "\n")
    print(f"Results in {work}")
    if args.candidate and reports["candidate"]["failures"]:
        raise SystemExit(", ".join(reports["candidate"]["failures"]))


if __name__ == "__main__":
    main()
