#!/bin/sh
# Builds and runs both the Rust store/engine microbenchmarks and the end-to-end
# Python workflow measurements for issue #765, writing results/<system>-<arch>.md,
# results/<system>-<arch>.csv, and results/<system>-<arch>-python.json.
set -eu
cd "$(dirname "$0")"

system=$(uname -s | tr '[:upper:]' '[:lower:]')
[ "$system" = darwin ] && system=macos
name="$system-$(uname -m)"
mkdir -p results

machine() {
    if [ "$system" = macos ]; then
        echo "- CPU: $(sysctl -n machdep.cpu.brand_string), $(sysctl -n hw.perflevel0.physicalcpu) performance and $(sysctl -n hw.perflevel1.physicalcpu) efficiency cores"
        echo "- Memory: $(($(sysctl -n hw.memsize) / 1073741824)) GiB"
        echo "- System: macOS $(sw_vers -productVersion) ($(sw_vers -buildVersion))"
    else
        echo "- CPU: $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2 | sed 's/^ //')"
        echo "- Memory: $(awk '/MemTotal/ { print int($2 / 1048576) " GiB" }' /proc/meminfo)"
        echo "- System: $(uname -sr)"
    fi
    echo "- Rust: $(rustc -V)"
    echo "- Date: $(date -u +%Y-%m-%d)"
}

cargo build --release --locked --quiet
{
    echo "# Structure settling measurements (#765), $name"
    echo
    echo "Generated by \`evidence/structure-settling/run.sh\`; see \`README.md\` for methodology and analysis."
    echo
    machine
    echo
    ./target/release/structure-settling-bench "results/$name.csv"
    echo
    uv run --no-sync --project ../.. python measure_python.py "results/$name-python.json"
} > "results/$name.md"
echo "wrote results/$name.md, results/$name.csv, and results/$name-python.json"
