# ruff: noqa: INP001 - a script, not a package.
"""Compare pyropdf's to_json and to_chunks with PyMuPDF 2.0's on the fixture of tests/test_document_chunks.py.

Run each side in its own environment, then the report. The pyropdf side also writes the fixture,
which the PyMuPDF side reads:

    uv run python evidence/document-chunks/compare.py pyropdf target/chunks.pdf > target/chunks-pyropdf.json
    uv run --no-project --python 3.13 --with 'pymupdf==2.0' --with 'pymupdf4llm==2.0' \
        python evidence/document-chunks/compare.py pymupdf target/chunks.pdf > target/chunks-pymupdf.json
    uv run python evidence/document-chunks/compare.py report target/chunks-pyropdf.json \
        target/chunks-pymupdf.json > evidence/document-chunks/results/report.md

pyropdf's chunk budget counts characters and PyMuPDF's counts tokens, so each run uses a small budget
(60 characters, 15 tokens) that splits the fixture's long paragraph, and the default one.
"""

from __future__ import annotations

import contextlib
import json
import sys
from pathlib import Path
from typing import Any


def _round(box: tuple[float, ...] | list[float]) -> list[float]:
    return [round(float(value), 1) for value in box]


def run_pyropdf(path: Path) -> dict[str, Any]:
    """Write the fixture to ``path`` and return pyropdf's elements and chunks of it."""
    import pyropdf  # noqa: PLC0415 - each side imports only its own library

    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tests"))
    import test_document_chunks  # noqa: PLC0415

    path.write_bytes(test_document_chunks.fixture_bytes())
    document = pyropdf.open(path.read_bytes())
    pages = json.loads(document.to_json())["pages"]
    elements = [
        {"page": page["index"], "kind": element["kind"], "bbox": _round(element["bbox"]), "text": element["text"]}
        for page in pages
        for element in page["elements"]
    ]
    runs = {}
    for name, budget in (("small", 60), ("default", 2000)):
        runs[name] = [
            {"pages": list(chunk.pages), "section": list(chunk.section), "text": chunk.text}
            for chunk in document.to_chunks(max_chars=budget)
        ]
    return {"elements": elements, "chunks": runs}


def run_pymupdf(path: Path) -> dict[str, Any]:
    """Return PyMuPDF's elements and chunks of the fixture at ``path``."""
    import pymupdf  # noqa: PLC0415

    document = pymupdf.open(path)
    pages = json.loads(document.to_json())["pages"]
    elements = [
        {
            "page": page["page_number"] - 1,
            "kind": box["boxclass"],
            "bbox": _round((box["x0"], box["y0"], box["x1"], box["y1"])),
            "text": " ".join(span["text"] for line in box["textlines"] or () for span in line["spans"]),
        }
        for page in pages
        for box in page["boxes"]
    ]
    runs = {}
    for name, budget in (("small", 15), ("default", None)):
        options = {} if budget is None else {"max_tokens": budget}
        runs[name] = [
            {
                "pages": list(range(chunk.metadata.page_start - 1, chunk.metadata.page_end)),
                "section": list(chunk.metadata.section_path),
                "text": chunk.text,
            }
            for chunk in document.to_chunks(**options)
        ]
    return {"elements": elements, "chunks": runs}


def _table(rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(rows[0]) + " |", "| " + " | ".join("---" for _ in rows[0]) + " |"]
    lines += [
        "| " + " | ".join(cell.replace("|", "\\|").replace("\n", "<br>") for cell in row) + " |" for row in rows[1:]
    ]
    return "\n".join(lines)


def report(pyro: dict[str, Any], mupdf: dict[str, Any]) -> str:
    """Return both sides' results as Markdown tables."""
    out = ["# Document chunks: pyropdf and PyMuPDF 2.0", "", "Generated by `compare.py`.", ""]
    for name, side in (("pyropdf", pyro), ("PyMuPDF 2.0", mupdf)):
        out += [f"## Elements: {name}", ""]
        rows = [["page", "kind", "bbox", "text"]]
        rows += [[str(e["page"]), e["kind"], str(e["bbox"]), e["text"][:60]] for e in side["elements"]]
        out += [_table(rows), ""]
    for run in ("small", "default"):
        for name, side in (("pyropdf", pyro), ("PyMuPDF 2.0", mupdf)):
            out += [f"## Chunks ({run} budget): {name}", ""]
            rows = [["#", "pages", "section", "chars", "text"]]
            rows += [
                [str(i), str(c["pages"]), " / ".join(c["section"]), str(len(c["text"])), c["text"][:80]]
                for i, c in enumerate(side["chunks"][run])
            ]
            out += [_table(rows), ""]
    return "\n".join(out)


def main() -> None:
    """Run one side, or the report, as the first argument says."""
    mode = sys.argv[1]
    if mode == "report":
        sides = [json.loads(Path(path).read_text(encoding="utf-8")) for path in sys.argv[2:4]]
        sys.stdout.write(report(*sides))
        return
    path = Path(sys.argv[2])
    # pymupdf4llm prints its parser's messages, which would mix with the JSON.
    with contextlib.redirect_stdout(sys.stderr):
        result = run_pyropdf(path) if mode == "pyropdf" else run_pymupdf(path)
    sys.stdout.write(json.dumps(result, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
